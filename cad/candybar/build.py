from __future__ import annotations

import os
import shutil
from pathlib import Path

import FreeCAD as App

from . import check, export, hardware, massing, model, panel, params, render, style

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = "candybar"
SAVED = f"{DOCUMENT}.FCStd"
NOTE = "Generated by cad/build.sh from cad/params/*.csv. A rebuild overwrites this file: put lasting changes in the CSV files."


def build_document(params_dir: Path = ROOT / "params", name: str = DOCUMENT) -> App.Document:
    """Create the parametric document. Safe to call from a running GUI session.

    A document of the same name is replaced. If the build fails, the document
    it started is closed again, so a GUI session is not left with half a model.
    """
    rows = params.load(Path(params_dir))
    if name in App.listDocuments():
        if App.GuiUp and App.Gui.getDocument(name).Modified:
            raise RuntimeError(f"{name} is open with unsaved changes. Save or close it in FreeCAD first.")
        App.closeDocument(name)
    doc = App.newDocument(name)
    try:
        _populate(doc, rows)
    except BaseException:
        App.closeDocument(doc.Name)
        raise
    return doc


def _populate(doc: App.Document, rows: list[params.Param]) -> None:
    params.write_sheet(doc, rows)
    button_count = _button_count_fixed_at_build(doc)
    builder = model.Model(doc, (row.name for row in rows))
    hardware.build(builder)
    panel.build(builder, button_count)
    massing.build(builder)
    doc.Comment = NOTE
    doc.recompute()
    style.apply(doc)
    style.frame(doc)


def _button_count_fixed_at_build(doc: App.Document) -> int:
    count = params.value(doc, "btn_count")
    if count not in panel.BUTTON_COUNTS:
        raise params.ParamError(f"btn_count must be one of {panel.BUTTON_COUNTS}, not {count:g}")
    return int(count)


def run(params_dir: Path, out_dir: Path, renders: bool = True) -> check.Report:
    """Build into `out_dir`, replacing the outputs of an earlier run, and return the check report.

    The saved document has no view settings yet; `decorate` adds them in a GUI process.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    _clear(out_dir)
    doc = build_document(params_dir)
    try:
        doc.saveAs(str(out_dir / SAVED))
        report = check.run(doc)
        check.write(report, out_dir)
        export.write(doc, out_dir)
        if renders:
            render.write(doc, out_dir)
        return report
    finally:
        App.closeDocument(doc.Name)


def _clear(out_dir: Path) -> None:
    """Remove earlier outputs, so a failed build cannot leave stale results that look current."""
    for name in (SAVED, *check.OUTPUTS, *export.OUTPUTS, *render.OUTPUTS):
        path = out_dir / name
        if path.is_dir():
            shutil.rmtree(path)
        else:
            path.unlink(missing_ok=True)


def main() -> int:
    params_dir = Path(os.environ.get("CANDYBAR_PARAMS") or ROOT / "params")
    out_dir = Path(os.environ.get("CANDYBAR_OUT") or ROOT / "out")
    report = run(params_dir, out_dir, renders=os.environ.get("CANDYBAR_RENDER") != "0")
    print(check.summary(report))
    print(f"outputs in {out_dir}")
    return 1 if report.count(check.FAIL) else 0
